
"""Define the interface for task storage implementations."""

from abc import ABC, abstractmethod

from app.data.pydantic_objects import PLTask


class TaskRepository(ABC):
    """Abstract interface for accessing and managing tasks.

    Concrete repository implementations are responsible for handling
    the underlying task storage mechanism.
    """

    @abstractmethod
    def add(self, task: PLTask) -> PLTask:
        """Save a new task.

        Args:
            task: The task to save.

        Returns:
            The saved task, including any values generated by storage.
        """
        raise NotImplementedError

    @abstractmethod
    def get_by_id(self, task_id: int) -> PLTask | None:
        """Retrieve a task using its unique ID.

        Args:
            task_id: The ID of the task to retrieve.

        Returns:
            The matching task, or None if no task exists with that ID.
        """
        raise NotImplementedError

    @abstractmethod
    def get_by_name(self, name: str) -> PLTask | None:
        """Retrieve a task using its name.

        Args:
            name: The exact name of the task to retrieve.

        Returns:
            The matching task, or None if no task exists with that name.
        """
        raise NotImplementedError

    @abstractmethod
    def delete(self, name_or_id: str | int) -> None:
        """Delete a task using its name or ID.

        Args:
            name_or_id: The name or integer ID of the task to delete.

        Raises:
            TypeError: If the supplied identifier is not a string or integer.
        """
        raise NotImplementedError

    @abstractmethod
    def list(self, task_type: str | None = None) -> list[PLTask]:
        """Retrieve tasks, optionally filtering by task type.

        Args:
            task_type: The task type to filter by. If None, all tasks
                are returned.

        Returns:
            A list of matching tasks. Returns an empty list if no tasks
            match the requested filter.
        """
        raise NotImplementedError

    @abstractmethod
    def update(self, task: PLTask) -> PLTask | None:
        """Update an existing task.

        Args:
            task: The task containing the updated values. Its ID identifies
                the existing task.

        Returns:
            The updated task, or None if the task does not exist or
            does not have an ID.
        """
        raise NotImplementedError
